#!/usr/bin/env node
'use strict';

/**
 * Replace require() calls to scripts/lib/*.js in hooks/*.js with inline
 * implementations, making hooks single-file.
 *
 * Why needed: hooks may be copied elsewhere by the host for execution. The
 * test-git-gate.js version trace test copies git-gate.js alone to a temp
 * directory with a fake SKILL.md beside it, verifying it reads the version
 * from **its own directory** walking up. `require('../scripts/lib/bash-lex.js')`
 * there would inevitably `Cannot find module`, crashing the hook with no trace.
 *
 * Why build instead of hand-write: hand-written inlines will inevitably drift
 * from source modules. Source module scripts/lib/bash-lex.js is the single
 * source of truth; this script injects it into the hook; self-check verifies
 * "inline content == source module content"; drift = failure.
 *
 * Usage:
 *   node scripts/inline-hooks.js           # write (idempotent)
 *   node scripts/inline-hooks.js --check   # only verify sync; exit 1 if out of sync
 *
 * Generated blocks are wrapped by MARKERs; repeated runs only replace that block.
 */

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const BEGIN = '// ==== INLINED (generated by scripts/inline-hooks.js; edit scripts/lib instead) ====';
const END = '// ==== END INLINED ====';

const HOOKS = [
  { file: 'hooks/git-gate.js', modules: ['bash-lex'] },
  { file: 'hooks/opsgate.js', modules: ['bash-lex', 'ops-policy'] },
];

const CHECK_ONLY = process.argv.includes('--check');

/** Read source module, strip shebang and 'use strict' (hook already has its own). */
function loadModule(name) {
  const p = path.join(ROOT, 'scripts', 'lib', `${name}.js`);
  let src = fs.readFileSync(p, 'utf8');
  src = src.replace(/^#!.*\n/, '');
  src = src.replace(/^\s*'use strict';\s*/m, '');
  // Remove module export statements — exported objects are destructured via const in the hook
  const exp = src.match(/module\.exports\s*=\s*\{([^}]*)\};?\s*$/m);
  if (!exp) throw new Error(`scripts/lib/${name}.js: module.exports not found`);
  const names = exp[1].split(',').map(s => s.trim()).filter(Boolean);
  src = src.replace(exp[0], '');
  return { name, body: src.trimEnd(), exports: names };
}

/** Generate inline block. */
function buildBlock(hookPath, moduleNames) {
  const mods = moduleNames.map(loadModule);
  const parts = [];
  parts.push(BEGIN);
  parts.push('/*');
  parts.push(` * Source: scripts/lib/${mods.map(m => m.name + '.js').join(' + ')}`);
  parts.push(' * This block is generated by scripts/inline-hooks.js — **do not edit here**;');
  parts.push(' * edit the source module under scripts/lib/ and re-run inline-hooks.js.');
  parts.push(' * self-check verifies inline content matches the source module; drift = failure.');
  parts.push(' */');
  for (const m of mods) {
    parts.push(`/* ---------- scripts/lib/${m.name}.js ---------- */`);
    parts.push(m.body);
    parts.push('');
  }
  // Note: **no longer generate generic destructured exports**.
  // Source module functions are function declarations, naturally available in
  // scope after inlining; the hook's original require lines have been removed
  // by spliceBlock. Previously added `const { x } = (() => ({ x }))()` —
  // duplicates existing function declarations, causing
  // `Identifier has already been declared`, and x inside IIFE is in TDZ.
  //
  // Exception: if the hook uses `OPS.assessCommand(...)` style **object access**
  // (original require was `const OPS = require(...)`), OPS no longer exists
  // after inlining; must add an object alias.
  const hookSrc = fs.readFileSync(hookPath, 'utf8');
  if (/\bOPS\s*\./.test(hookSrc)) {
    parts.push('// Compatibility alias for the original `OPS.xxx` object access form in the hook');
    parts.push('// (original require variable name was OPS)');
    parts.push('const OPS = { ' + loadModule('ops-policy').exports.join(', ') + ' };');
    parts.push('');
  }
  parts.push(END);
  return parts.join('\n');
}

/** Replace existing block in the hook, or insert at the first require line position. */
function spliceBlock(src, block) {
  const b = src.indexOf(BEGIN);
  const e = src.indexOf(END);
  if (b !== -1 && e !== -1 && e > b) {
    return { text: src.slice(0, b) + block + src.slice(e + END.length), replaced: true };
  }

  // Recognize both require forms:
  //   const { a, b } = require('../scripts/lib/x.js');   <- destructured
  //   const OPS = require('../scripts/lib/ops-policy.js'); <- direct assignment
  const isRequire = (line) =>
    /^\s*const (?:\{[^}]*\}|[A-Za-z_$][\w$]*)\s*=\s*require\([\x27"]\.\.\/scripts\/lib\/[\w.-]+[\x27"]\);/.test(line);

  const lines = src.split('\n');
  const firstIdx = lines.findIndex(isRequire);
  if (firstIdx === -1) {
    throw new Error('No scripts/lib require line found; cannot locate insertion point');
  }

  // Remove **all** require lines, only insert block once at the original first position.
  // If every require line were replaced with a block, opsgate would get two copies
  // of source code -> duplicate declaration crash.
  const out = [];
  let inserted = false;
  lines.forEach((line) => {
    if (isRequire(line)) {
      if (!inserted) { out.push(block); inserted = true; }
      return;          // require line discarded
    }
    out.push(line);
  });
  return { text: out.join('\n'), replaced: false };
}

let allOk = true;
for (const hook of HOOKS) {
  const p = path.join(ROOT, hook.file);
  const before = fs.readFileSync(p, 'utf8');
  const block = buildBlock(p, hook.modules);
  const { text: after, replaced } = spliceBlock(before, block);

  if (CHECK_ONLY) {
    if (before !== after) {
      console.error(`X ${hook.file}: inline block out of sync with scripts/lib/ (re-run inline-hooks.js)`);
      allOk = false;
    } else {
      console.log(`[OK] ${hook.file}: inline content matches source modules`);
    }
    continue;
  }

  if (before === after) { console.log(`[OK] ${hook.file}: already up to date, no changes needed`); continue; }
  fs.writeFileSync(p, after);
  console.log(`[OK] ${hook.file}: ${replaced ? 'replaced' : 'inserted'} inline block (${hook.modules.join(' + ')})`);
}

process.exit(CHECK_ONLY && !allOk ? 1 : 0);
