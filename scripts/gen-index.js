#!/usr/bin/env node
'use strict';

/**
 * Regenerate modules/index.md from the filesystem.
 * Hand-maintained indexes inevitably drift (v15's index once stayed at v9.0).
 * This script makes the index drift-proof.
 * Usage: node scripts/gen-index.js [--check]   --check only verifies consistency with disk
 */

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const MODULES = path.join(ROOT, 'modules');
const OUT = path.join(MODULES, 'index.md');
const HISTORICAL_MARK = 'Historical design drafts (v9-v13 era)';

function walk(dir) {
  const out = [];
  for (const e of fs.readdirSync(dir, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) out.push(...walk(p));
    else if (e.name.endsWith('.md')) out.push(p);
  }
  return out;
}

function describe(file) {
  const text = fs.readFileSync(file, 'utf8');
  const lines = text.split('\n');
  const title = (lines.find(l => l.startsWith('# ')) || '# (untitled)').slice(2).trim();
  let desc = '';
  for (const l of lines) {
    if (l.includes(HISTORICAL_MARK) || l.startsWith('> Authoritative definition') || l.startsWith('> Index and state')) continue;
    if (l.startsWith('> ')) { desc = l.slice(2).trim(); break; }
  }
  // Strip markdown syntax before truncating: otherwise [x](y) gets cut in half,
  // producing broken links in the index
  desc = desc
    .replace(/\[([^\]]+)\]\([^)]*\)/g, '$1')   // links keep text
    .replace(/\*\*/g, '').replace(/[`>|]/g, '')
    .trim();
  if (desc.length > 60) desc = desc.slice(0, 60).trim() + '...';
  return { title, desc, historical: text.includes(HISTORICAL_MARK) };
}

const GROUPS = [
  ['core', 'Core modules (including marked historical materials)'],
  ['stages', 'Stage definitions (authoritative)'],
  ['paths', 'Execution paths (authoritative)'],
  ['automation', 'Automation layer (historical design drafts, not implemented)'],
];

function build() {
  const files = walk(MODULES).filter(f => f !== OUT);
  const byGroup = {};
  for (const f of files) {
    const rel = path.relative(MODULES, f);
    const top = rel.split(path.sep)[0];
    (byGroup[top] = byGroup[top] || []).push({ rel, file: f, ...describe(f) });
  }

  const lines = [];
  lines.push('# Hello Dev Modules');
  lines.push('');
  lines.push('> This file is auto-generated by `node scripts/gen-index.js`. Do not edit manually.');
  lines.push('> Authoritative judgment: files with "Historical design drafts" marker at top are non-authoritative; current workflow does not read them.');
  lines.push('');
  lines.push('## Authoritativeness Rules');
  lines.push('');
  lines.push('| Topic | Authoritative source | Non-authoritative |');
  lines.push('|-------|---------------------|-------------------|');
  lines.push('| Process and stages | `../SKILL.md` master contract, `stages/` refines as needed | `../agents/`, `automation/` |');
  lines.push('| Git risk classification | `core/approval/git-gate.md` | -- |');
  lines.push('| State and recovery | `core/state-protocol.md` + `../scripts/state.js` | Old flowcharts and historical examples |');
  lines.push('| Memory | `../SKILL.md` "Memory" chapter | `core/memory/` |');
  lines.push('');

  for (const [key, label] of GROUPS) {
    const items = byGroup[key];
    if (!items || !items.length) continue;
    lines.push(`## ${label}`);
    lines.push('');
    lines.push('| File | Title | Description |');
    lines.push('|------|-------|-------------|');
    for (const it of items) {
      const banner = it.historical ? ' [HISTORICAL]' : '';
      lines.push(`| [${it.rel}](${it.rel.split(path.sep).join('/')}) | ${it.title} | ${it.desc}${banner} |`);
    }
    lines.push('');
  }

  const extra = Object.keys(byGroup).filter(k => !GROUPS.some(([g]) => g === k));
  if (extra.length) {
    lines.push('## Other');
    lines.push('');
    for (const k of extra) {
      for (const it of byGroup[k]) lines.push(`- [${it.rel}](${it.rel}) -- ${it.title}`);
    }
    lines.push('');
  }

  lines.push('## Supporting files outside modules/');
  lines.push('');
  lines.push('| Path | Purpose |');
  lines.push('|------|---------|');
  lines.push('| `../hooks/git-gate.js` | Git risk classification (registered PreToolUse/Bash host only) |');
  lines.push('| `../hooks/opsgate.js` | Ops command risk classification (registered PreToolUse/Bash host only) |');
  lines.push('| `../references/runtime-adapters.md` | Host capabilities and installation sync boundaries |');
  lines.push('| `../hooks/test-git-gate.js` | git-gate unit tests (classification cases + mode and probe cases, verified by actual runs) |');
  lines.push('| `../hooks/test-opsgate.js` | opsgate unit tests (classification + contract + mode switch + git boundary) |');
  lines.push('| `../references/scenario-replay.md` | Scenario experience replay (manual checklist, not auto-executed) |');
  lines.push('| `../references/cost-metrics.md` | Process cost metrics and regression baselines |');
  lines.push('| `../references/automation-charter.md` | Automation authorization contract (auto-take-effect vs requires manual approval) |');
  lines.push('| `../templates/design-decision.md` | Structured design decision record (five questions) |');
  lines.push('| `../scripts/release-check.sh` | Source / install copy / runtime three-way consistency |');
  lines.push('| `../scripts/state.js` | State file read/write / recovery / diff report |');
  lines.push('| `../scripts/gen-index.js` | Regeneration script for this index |');
  lines.push('| `../scripts/check-links.js` | Markdown broken link check (regression-verifiable) |');
  lines.push('| `../scripts/check-gate-consistency.js` | Git risk table vs hook classification consistency check |');
  lines.push('| `../scripts/check-opsgate-consistency.js` | Ops risk table vs hook classification consistency check |');
  lines.push('| `../scripts/lib/ops-policy.js` | Ops command risk policy (shared by opsgate and runbook validation) |');
  lines.push('| `../scripts/lib/ops-approval.js` | Execution intent digest and approval credential (stepDigest) |');
  lines.push('| `../scripts/lib/decomposition.js` | Wave derivation and execution-order analysis (single source for state.js and codex-prompt.js) |');
  lines.push('| `../scripts/test-decomposition.js` | Decomposition order analysis regressions (order independence, coverage, --replace) |');
  lines.push('| `../scripts/check-doc-commands.js` | Doc commands vs CLI command table consistency check |');
  lines.push('| `../scripts/check-collaboration-matrix.js` | Collaboration matrix vs state/memory/skill detection consistency check |');
  lines.push('| `../scripts/detect-skills.js` | Installed skill detection (dereference symlinks for dedup; generates collaboration matrix S4.2) |');
  lines.push('| `../scripts/test-detect-skills.js` | Skill detector behavior and doc drift injection tests |');
  lines.push('| `../scripts/codex-prompt.js` | Codex sub-agent prompt constructor (reads decomposition, generates prompts per codex.md spec) |');
  lines.push('| `../scripts/test-codex-prompt.js` | Codex prompt constructor unit tests (wave derivation, file conflict, prompt structure) |');
  lines.push('| `../scripts/check-state-fields.js` | Dead field detection |');
  lines.push('| `../scripts/test-state.js` | State protocol full lifecycle assertions |');
  lines.push('| `../scripts/test-ops-approval.js` | Execution intent approval unit tests (digest stability, invalidation judgment) |');
  lines.push('| `../scripts/test-ops-approval.sh` | Execution intent approval end-to-end state gate assertions |');
  lines.push('| `../scripts/self-check.sh` | Run all invariants with a single command |');
  lines.push('| `../docs/progress_coding/_RULES.md` | Development process documentation mandatory rules |');
  lines.push('');
  lines.push('---');
  lines.push('');
  lines.push(`Generated: ${new Date().toISOString().slice(0, 10)} | Covering ${files.length} module files`);
  lines.push('');
  return lines.join('\n');
}

const content = build();
if (process.argv.includes('--check')) {
  const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  const norm = s => s.replace(/Generated: .*/, '').trim();
  if (norm(cur) !== norm(content)) { console.log('X modules/index.md out of sync with disk, run node scripts/gen-index.js'); process.exit(1); }
  console.log('[OK] modules/index.md is consistent with disk');
} else {
  fs.writeFileSync(OUT, content, 'utf8');
  console.log(`[OK] Regenerated modules/index.md (${content.split('\n').length} lines)`);
}
